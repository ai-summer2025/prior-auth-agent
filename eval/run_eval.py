"""Evaluate priorauth.

1. Engine: 14 structured requests with gold outcomes (eval/requests.json), covering every
   outcome, every policy, uncovered diagnoses and missing facts.
2. Extraction: 5 synthetic notes with gold facts and gold outcome (eval/notes_gold.json).
   UNSAFE = a note-derived request reaches meets_criteria when the gold outcome is not.

  python eval/run_eval.py [--llm] [--check]
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
sys.path.insert(0, str(ROOT.parent / "src"))

from priorauth.engine import determine  # noqa: E402
from priorauth.pipeline import request_from_dict, request_from_note  # noqa: E402
from priorauth.policies import load_policies  # noqa: E402


def eval_engine(policies):
    cases = json.loads((ROOT / "requests.json").read_text())
    errors = []
    for c in cases:
        got = determine(request_from_dict(c["request"]), policies).outcome
        if got != c["expected"]:
            errors.append(f"{c['request']['id']}: expected {c['expected']}, got {got}")
    return len(cases), errors


def _eq(a, b):
    if isinstance(a, list) or isinstance(b, list):
        return set(a or []) == set(b or [])
    if isinstance(a, bool) or isinstance(b, bool):
        return a is b
    try:
        return abs(float(a) - float(b)) < 1e-6
    except (TypeError, ValueError):
        return False


def eval_extraction(policies, use_llm=False, client=None):
    gold = json.loads((ROOT / "notes_gold.json").read_text())
    ok = n = outcome_ok = unsafe = 0
    errors = []
    for nid, g in sorted(gold.items()):
        text = (ROOT / "notes" / f"{nid}.txt").read_text()
        req = request_from_note(text, g["service_code"], g["diagnosis_codes"], nid, use_llm, client, policies)
        for k, v in g["facts"].items():
            n += 1
            if k in req.facts and _eq(req.facts[k], v):
                ok += 1
            else:
                errors.append(f"{nid} {k}: expected {v}, got {req.facts.get(k, '(missing)')}")
        outcome = determine(req, policies).outcome
        outcome_ok += outcome == g["expected"]
        if outcome != g["expected"]:
            bad = outcome == "meets_criteria"
            unsafe += bad
            errors.append(f"{nid} outcome: expected {g['expected']}, got {outcome}" + (" (UNSAFE)" if bad else ""))
    return {"fact_accuracy": ok / n, "outcome_accuracy": outcome_ok / len(gold), "unsafe": unsafe,
            "n": len(gold), "errors": errors}


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--llm", action="store_true")
    ap.add_argument("--check", action="store_true")
    args = ap.parse_args()
    policies = load_policies()
    n, engine_errors = eval_engine(policies)
    ext = {"rules": eval_extraction(policies)}
    if args.llm:
        from priorauth.llm import client_from_env
        ext["llm"] = eval_extraction(policies, True, client_from_env())
    out = ["# Evaluation results", "", "Generated by `python eval/run_eval.py`. All data is synthetic.", "",
           f"## Policy engine ({n} structured requests)", ""]
    out += [f"- {e}" for e in engine_errors] or [f"All {n} outcomes match."]
    out += ["", f"## Note to determination ({ext['rules']['n']} notes)", "",
            "| Extractor | Fact accuracy | Outcome accuracy | Unsafe approvals |", "|---|---|---|---|"]
    for m, r in ext.items():
        out.append(f"| {m} | {r['fact_accuracy']:.2f} | {r['outcome_accuracy']:.2f} | {r['unsafe']} |")
    if "llm" not in ext:
        out.append("| llm | not run here: requires credentials. Run `python eval/run_eval.py --llm` | | |")
    for m, r in ext.items():
        out += ["", f"### {m} errors", ""] + ([f"- {e}" for e in r["errors"]] or ["- none"])
    (ROOT / "RESULTS.md").write_text("\n".join(out) + "\n")
    print("\n".join(out))
    if args.check:
        base = json.loads((ROOT / "baseline.json").read_text())
        r = ext["rules"]
        if engine_errors or r["unsafe"] > 0 or r["fact_accuracy"] < base["rules_fact_accuracy"]:
            print("REGRESSION", file=sys.stderr)
            return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
